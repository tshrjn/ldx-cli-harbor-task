#!/usr/bin/env python3
"""Regenerate build/refldx-src/fam_help.c from the allowed[] list each command declares.

`refldx help <command>` prints flag NAMES and the positional count -- never semantics.
SPEC v2 removes the per-command flag tables entirely, so this is the only place the flag
surface is legible; an audit found 153 of one run's 344 grid failures reduced to a single
undiscoverable flag name. Run this after adding or changing any command, then rebuild.
"""
import re, glob, pathlib, sys

SRC = pathlib.Path(__file__).resolve().parent / "refldx-src"

def main() -> int:
    name2fn, fn2flags, fn2pos = {}, {}, {}
    for f in glob.glob(str(SRC / "*.c")):
        text = pathlib.Path(f).read_text()
        for m in re.finditer(r'\{"([a-z0-9-]+)",\s*(cmd_[a-z0-9_]+),', text):
            name2fn[m.group(1)] = m.group(2)
        for m in re.finditer(r'static int (cmd_[a-z0-9_]+)\(int argc, char \*\*argv\) \{(.*?)\n\}', text, re.S):
            fn, body = m.group(1), m.group(2)
            a = re.search(r'static const char \*allowed\[\]\s*=\s*\{(.*?)\};', body, re.S)
            fn2flags[fn] = re.findall(r'"([a-z0-9-]+)"', a.group(1)) if a else []
            p = re.search(r'positional\(&a,\s*(\d+)\)', body)
            fn2pos[fn] = int(p.group(1)) if p else 0
    rows = [(n, fn2flags.get(fn, []), fn2pos.get(fn, 0))
            for n, fn in sorted(name2fn.items()) if n != "gen-score"]
    out = ['''/* ------------------------------------------------------------------ */
/* help <command> -- the flag surface, and nothing else                */
/* ------------------------------------------------------------------ */
/*
 * GENERATED by build/gen_help_table.py.  Do not hand-edit: regenerate.
 *
 * Flag NAMES and the positional count only.  What a flag means, what it accepts
 * and what the command does stay discoverable only by running the tool, which is
 * the method the whole task is built on.  What this removes is guessing a flag's
 * NAME out of thin air, which measures luck rather than capability.
 */

typedef struct { const char *name; const char *flags; int npos; } HelpRow;

static const HelpRow HELP_ROWS[] = {''']
    out += ['    {"%s", "%s", %d},' % (n, " ".join(fl), np) for n, fl, np in rows]
    out.append('''};

static int help_command(const char *name) {
    size_t i;
    for (i = 0; i < sizeof HELP_ROWS / sizeof HELP_ROWS[0]; i++) {
        if (strcmp(HELP_ROWS[i].name, name) != 0) continue;
        printf("usage: ldx %s", HELP_ROWS[i].name);
        if (HELP_ROWS[i].flags[0]) {
            const char *p = HELP_ROWS[i].flags;
            while (*p) {
                const char *e = strchr(p, ' ');
                size_t n2 = e ? (size_t)(e - p) : strlen(p);
                printf(" [--%.*s]", (int)n2, p);
                p = e ? e + 1 : p + n2;
            }
        }
        if (HELP_ROWS[i].npos == 1) printf(" <in.ldx>");
        else if (HELP_ROWS[i].npos >= 2) printf(" <in.ldx> <out.ldx>");
        printf("\\n");
        printf("flags: %s\\n", HELP_ROWS[i].flags[0] ? HELP_ROWS[i].flags : "(none)");
        printf("Flag names only. What each does, its range, and the command's semantics are\\n"
               "discoverable by running the tool.\\n");
        return EXIT_OK;
    }
    return -1;
}''')
    (SRC / "fam_help.c").write_text("\n".join(out) + "\n")
    print(f"fam_help.c regenerated: {len(rows)} commands")
    return 0

if __name__ == "__main__":
    sys.exit(main())
